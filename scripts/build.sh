#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

VERSION_NAME="${VERSION_NAME:-1.4.5}"
VERSION_CODE="${VERSION_CODE:-15}"

sdk_path="${DEBUGGUARD_SDK:-$HOME/.cache/debugguard-sdk}"
platform="$sdk_path/platforms/android-36/android.jar"
tools="$sdk_path/build-tools/android-16"
test -f "$platform" || { echo "Android API 36 not found: $platform" >&2; exit 1; }
test -x "$tools/aapt2" || { echo "Android build-tools 36 not found: $tools" >&2; exit 1; }

# Keep Java BuildInfo in sync with the APK version.
cat > app/src/main/java/dev/satin/debugguard/BuildInfo.java <<EOF
package dev.satin.debugguard;

/** Generated by scripts/build.sh — do not edit by hand. */
public final class BuildInfo {
    public static final String VERSION_NAME = "${VERSION_NAME}";
    public static final int VERSION_CODE = ${VERSION_CODE};

    private BuildInfo() {}
}
EOF

mkdir -p build/classes build/dex build/compiled-res
rm -f build/compiled-res/*
"$tools/aapt2" compile -o build/compiled-res/ app/src/main/res/values/strings.xml
"$tools/aapt2" compile -o build/compiled-res/ app/src/main/res/values/colors.xml
"$tools/aapt2" compile -o build/compiled-res/ app/src/main/res/values/themes.xml
"$tools/aapt2" compile -o build/compiled-res/ app/src/main/res/values-night/themes.xml
"$tools/aapt2" compile -o build/compiled-res/ app/src/main/res/xml/shortcuts.xml
mapfile -t flat_res < <(find build/compiled-res -type f -name '*.flat' | sort)
"$tools/aapt2" link -o build/unsigned.apk \
  --manifest app/src/main/AndroidManifest.xml \
  -I "$platform" \
  --min-sdk-version 29 \
  --target-sdk-version 35 \
  --version-code "$VERSION_CODE" \
  --version-name "$VERSION_NAME" \
  "${flat_res[@]}"
javac --release 17 -cp "$platform" -d build/classes app/src/main/java/dev/satin/debugguard/*.java
jar cf build/classes.jar -C build/classes .
"$tools/d8" --lib "$platform" --min-api 29 --output build/dex build/classes.jar
cp build/unsigned.apk build/unaligned.apk
(cd build/dex && zip -q -u ../unaligned.apk classes.dex)
"$tools/zipalign" -f 4 build/unaligned.apk build/aligned.apk
if [[ ! -f build/debug.keystore ]]; then
  keytool -genkeypair -alias debug -keyalg RSA -keysize 2048 -validity 3650 -dname 'CN=DebugGuard' -keystore build/debug.keystore -storepass android -keypass android >/dev/null 2>&1
fi
"$tools/apksigner" sign --ks build/debug.keystore --ks-pass pass:android --key-pass pass:android --out build/debugguard.apk build/aligned.apk
cp -f build/debugguard.apk build/debugguard-poc.apk
"$tools/apksigner" verify --verbose build/debugguard.apk
echo "APK: build/debugguard.apk  (${VERSION_NAME} / ${VERSION_CODE})"
